"""
Patient State Representation for Digital Twin Engine.
This module contains the core structures for representing a virtual patient.
"""
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import Dict, List, Optional, Any
from collections import deque
import numpy as np
import pandas as pd
import uuid

@dataclass
class VitalSigns:
    """Current vital signs for a patient."""
    glucose_mg_dl: float = 0.0
    heart_rate_bpm: float = 0.0
    hrv_rmssd_ms: float = 0.0
    hrv_sdnn_ms: float = 0.0
    systolic_bp: float = 0.0
    diastolic_bp: float = 0.0
    spo2_pct: float = 98.0
    timestamp: Optional[datetime] = None

@dataclass
class RiskScores:
    """Current risk assessments for a patient."""
    glucose_spike_risk: float = 0.0
    cardiovascular_risk: float = 0.0
    composite_risk: float = 0.0
    glucose_predicted_values: List[float] = field(default_factory=list)
    glucose_confidence_lower: List[float] = field(default_factory=list)
    glucose_confidence_upper: List[float] = field(default_factory=list)
    risk_category: str = 'Low'
    last_updated: Optional[datetime] = None

@dataclass
class Alert:
    """A clinical alert generated by the twin engine."""
    alert_id: str
    severity: str  # CRITICAL, HIGH, MODERATE, INFO
    metric: str
    value: float
    threshold: float
    message: str
    timestamp: datetime
    acknowledged: bool = False
    
    def to_dict(self) -> dict:
        return {
            'alert_id': self.alert_id,
            'severity': self.severity,
            'metric': self.metric,
            'value': self.value,
            'threshold': self.threshold,
            'message': self.message,
            'timestamp': self.timestamp.isoformat() if self.timestamp else None,
            'acknowledged': self.acknowledged
        }

class PatientDigitalTwin:
    """
    The core digital representation of a patient.
    Maintains current state, history, risks, and alerts.
    """
    def __init__(self, patient_id: str, demographics: dict, medical_history: dict, medications: list):
        self.patient_id = patient_id
        self.demographics = demographics
        self.medical_history = medical_history
        self.medications = medications
        
        self.current_vitals = VitalSigns()
        self.current_risk = RiskScores()
        
        self.prediction_timeline: List[dict] = []
        self.alert_history: List[Alert] = []
        
        # 6 hours of minute-by-minute data (72 * 6 for 5 min intervals = 432, assuming minute-by-minute is 360)
        self.glucose_history = deque(maxlen=432)
        self.hr_history = deque(maxlen=432)

    def update_vitals(self, vital_signs: VitalSigns) -> None:
        """Update current vitals and append to history buffers."""
        self.current_vitals = vital_signs
        timestamp = vital_signs.timestamp or datetime.now()
        
        self.glucose_history.append({'timestamp': timestamp, 'value': vital_signs.glucose_mg_dl})
        self.hr_history.append({'timestamp': timestamp, 'value': vital_signs.heart_rate_bpm})

    def get_current_state(self) -> dict:
        """Return a complete snapshot of the patient's state."""
        return {
            'patient_id': self.patient_id,
            'demographics': self.demographics,
            'vitals': {k: v for k, v in self.current_vitals.__dict__.items() if k != 'timestamp'} | {
                'timestamp': self.current_vitals.timestamp.isoformat() if self.current_vitals.timestamp else None
            },
            'risk_scores': {
                'glucose_spike_risk': self.current_risk.glucose_spike_risk,
                'cardiovascular_risk': self.current_risk.cardiovascular_risk,
                'composite_risk': self.current_risk.composite_risk,
                'risk_category': self.current_risk.risk_category,
                'last_updated': self.current_risk.last_updated.isoformat() if self.current_risk.last_updated else None
            },
            'active_alerts': [a.to_dict() for a in self.get_active_alerts()],
            'prediction_timeline': self.prediction_timeline
        }

    def update_risk_scores(self, risk_scores: RiskScores) -> None:
        """Store new risk scores."""
        self.current_risk = risk_scores

    def add_alert(self, alert: Alert) -> None:
        """Add to alert history, maintaining a maximum of 100 alerts."""
        self.alert_history.append(alert)
        if len(self.alert_history) > 100:
            self.alert_history.pop(0)

    def get_active_alerts(self) -> List[Alert]:
        """Return all unacknowledged alerts."""
        return [alert for alert in self.alert_history if not alert.acknowledged]

    def acknowledge_alert(self, alert_id: str) -> None:
        """Mark a specific alert as acknowledged."""
        for alert in self.alert_history:
            if alert.alert_id == alert_id:
                alert.acknowledged = True
                break

    def get_glucose_history(self, minutes: int = 360) -> List[dict]:
        """Get recent glucose history up to the specified minutes."""
        history_list = list(self.glucose_history)
        return history_list[-minutes:] if minutes < len(history_list) else history_list

    def get_hr_history(self, minutes: int = 360) -> List[dict]:
        """Get recent heart rate history up to the specified minutes."""
        history_list = list(self.hr_history)
        return history_list[-minutes:] if minutes < len(history_list) else history_list

    def what_if_scenario(self, changes: dict) -> dict:
        """
        Evaluate estimated risk changes based on clinical rules.
        """
        base_cvd_risk = self.current_risk.cardiovascular_risk
        base_comp_risk = self.current_risk.composite_risk
        
        new_cvd_risk = base_cvd_risk
        new_comp_risk = base_comp_risk
        
        if changes.get('exercise_minutes', 0) >= 30:
            new_cvd_risk *= 0.85  # ~15% CVD risk reduction
            
        hba1c_change = changes.get('hba1c_change', 0.0)
        if hba1c_change < 0:
            reduction = min(abs(hba1c_change) * 0.20, 0.50)  # ~20% per 1% reduction, max 50%
            new_comp_risk *= (1 - reduction)
            
        if changes.get('stop_smoking', False):
            new_cvd_risk *= 0.70  # ~30% reduction over time
            
        return {
            'before': {
                'cardiovascular_risk': base_cvd_risk,
                'composite_risk': base_comp_risk
            },
            'after': {
                'cardiovascular_risk': new_cvd_risk,
                'composite_risk': new_comp_risk
            },
            'changes_applied': changes
        }

    def to_dict(self) -> dict:
        """Full serialization of the digital twin."""
        return {
            'patient_id': self.patient_id,
            'demographics': self.demographics,
            'medical_history': self.medical_history,
            'medications': self.medications,
            'current_vitals': self.current_vitals.__dict__,
            'current_risk': self.current_risk.__dict__,
            'alert_history': [a.to_dict() for a in self.alert_history],
            'glucose_history': [{'timestamp': t['timestamp'].isoformat(), 'value': t['value']} for t in self.glucose_history],
            'hr_history': [{'timestamp': t['timestamp'].isoformat(), 'value': t['value']} for t in self.hr_history],
        }

    def __repr__(self) -> str:
        return f"<PatientDigitalTwin(patient_id='{self.patient_id}')>"
